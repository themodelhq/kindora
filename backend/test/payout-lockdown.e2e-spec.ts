    await initiation.submitOutbox(attemptId);
    const reconciliation = app.get(PayoutReconciliationService);
    const beneficiaryRef = (await getTestPrisma().payoutBeneficiary.findFirstOrThrow({ where: { withdrawalId, provider: 'MOCK' } })).externalRef;
    const buildVerification = () =>
      getTestPrisma().payoutAttempt.findUniqueOrThrow({ where: { id: attemptId } }).then((a) => ({
        classification: 'SUCCESSFUL' as never,
        providerStatus: 'success',
        providerReference: a.providerTransferRef ?? undefined,
        amountMinor: a.amount,
        currency: a.currency,
        beneficiaryRef,
        evidence: { status: 'success' },
      }));

    // CASE 1 — the locked executor is MISSING: settlement is rejected.
    await getTestPrisma().payoutAttempt.update({ where: { id: attemptId }, data: { initiatedById: null } });
    const missingExecutor = await reconciliation.apply({ attemptId, source: 'RECONCILIATION_SWEEP' as never, verification: await buildVerification() });
    expect(missingExecutor.outcome).toBe('INTERNAL_STATE_MISMATCH');
    const blockedAudit = await getTestPrisma().auditLog.findFirstOrThrow({ where: { entityId: withdrawalId, action: 'PAYOUT_SETTLEMENT_BLOCKED_INVALID_APPROVAL_CYCLE' }, orderBy: { createdAt: 'desc' } });
