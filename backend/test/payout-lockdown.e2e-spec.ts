  async function waitFor(condition: () => Promise<boolean>, description: string, timeoutMs = 20_000): Promise<void> {
    const deadline = Date.now() + timeoutMs;
    while (Date.now() < deadline) {
      if (await condition()) return;
      await new Promise((r) => setTimeout(r, 100));
    }
    throw new Error(`condition not reached within ${timeoutMs}ms: ${description}`);
  }

