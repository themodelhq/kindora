// The paystack webhook endpoint verifies HMAC-SHA512 signatures over the raw
// body with the REAL verifier (PaymentsService.adapterFor only swaps the MOCK
// provider, not PAYSTACK). Set a known test secret BEFORE the app boots and
// sign the replayed delivery below so signature verification is exercised
// for real instead of being stubbed away.
process.env.PAYSTACK_SECRET_KEY = process.env.PAYSTACK_SECRET_KEY ?? 'sk_test_kindora_money_path_replay';

const PAYSTACK_SECRET = process.env.PAYSTACK_SECRET_KEY;

/** Signs a webhook payload exactly the way Paystack does (HMAC-SHA512 of the raw body). */
function signedPaystack(payload: Record<string, unknown>): { body: string; headers: Record<string, string> } {
  const body = JSON.stringify(payload);
  return {
    body,
    headers: { 'Content-Type': 'application/json', 'x-paystack-signature': createHmac('sha512', PAYSTACK_SECRET).update(body).digest('hex') },
  };
}

