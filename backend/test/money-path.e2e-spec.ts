  function totpCode(secretBase32: string, stepOffset = 0): string {
    const buf = base32Decode(secretBase32.replace(/=+$/, ''));
    const counter = BigInt(Math.floor(Date.now() / 1000 / TOTP_STEP_SECONDS)) + BigInt(stepOffset);
    return hotp(buf, counter);
  }

  // v1.0.9 — the two-step manual settlement issues TWO purpose-bound MFA
  // challenges for the same executor, so the enrollment secret is cached per
  // bearer and a second call exchanges against the already-active enrollment.
  const enrolledSecrets = new Map<string, string>();

  /** REAL fresh-MFA flow against real Redis; returns the single-use challenge token. */
  async function freshMfa(bearer: string, purpose: string, scope: string): Promise<string> {
    const status = await request(app.getHttpServer())
      .get('/api/v1/mfa/status')
      .set('Authorization', `Bearer ${bearer}`)
      .expect(200);
    const cached = enrolledSecrets.get(bearer);
    if (status.body.active) {
      if (!cached) {
        throw new Error('Admin already MFA-active in the persistent test DB — use fresh admin accounts for MFA');
      }
      return exchangeChallenge(bearer, purpose, scope, cached);
    }
    const enroll = await request(app.getHttpServer())
      .post('/api/v1/mfa/enroll')
      .set('Authorization', `Bearer ${bearer}`)
      .expect([200, 201]);
    const secret = enroll.body.secret as string;
    enrolledSecrets.set(bearer, secret);
    await request(app.getHttpServer())
      .post('/api/v1/mfa/confirm')
      .set('Authorization', `Bearer ${bearer}`)
      .send({ code: totpCode(secret) })
      .expect([200, 201]);
    return exchangeChallenge(bearer, purpose, scope, secret);
  }

  /** Step-boundary safe challenge exchange (+1 / +2 offsets across 30s windows). */
  async function exchangeChallenge(bearer: string, purpose: string, scope: string, secret: string): Promise<string> {
    for (const offset of [0, 1, 2]) {
      const attempt = await request(app.getHttpServer())
        .post('/api/v1/mfa/challenge')
        .set('Authorization', `Bearer ${bearer}`)
        .send({ purpose, scope, code: totpCode(secret, offset) });
      if (attempt.status === 200 || attempt.status === 201) {
        return attempt.body.challengeToken as string;
      }
      const msg = String(attempt.body?.message ?? '');
      if (!/already been used|Invalid or expired/.test(msg)) {
        throw new Error(`MFA challenge rejected unexpectedly (${attempt.status}): ${msg}`);
      }
    }
    throw new Error('No usable TOTP offset for MFA challenge — clock step boundary race persisted');
  }

