import request from 'supertest';
import type { NestExpressApplication } from '@nestjs/platform-express';
import { closeTestApp, createTestApp, getTestPrisma, maybeDescribe } from './setup';

/**
 * Webhook security integration tests (hardening spec §11 — PAYSTACK provider).
 *
 * IMPORTANT — how the provider boundary is handled: in PROVIDER_MODE=mock the
 * paystack webhook endpoint still uses the REAL PaystackService (adapterFor
 * only substitutes the MOCK provider, never PAYSTACK). This suite therefore
 * exercises the production signature scheme instead of a fake one:
 *  1. PAYSTACK_SECRET_KEY is set BEFORE the app boots and every valid
 *     delivery is signed with the real HMAC-SHA512(raw body) scheme —
 *     signature verification is real, not mocked;
 *  2. global fetch is stubbed ONLY for api.paystack.co hosts so the
 *     authoritative re-verification step (the webhook must re-check the
 *     transaction against the provider API before applying it) succeeds
 *     deterministically. Every other URL falls through to the real fetch.
 *
 * Covered invariants:
 *  - unknown event types are acknowledged (2xx) but NEVER change donation or
 *    ledger state (default-deny allowlist);
 *  - a successful charge is applied EXACTLY once: a duplicate delivery is
 *    absorbed via the (provider,eventId) uniqueness and no second ledger
 *    posting occurs (reference `donation:<id>` stays count 1);
 *  - refund.processed flips the donation to REFUNDED, posts compensating
 *    double-entry rows (type REFUND, reference `refund:<refundId>`) and
 *    restores the campaign raisedAmount;
 *  - an invalid signature is rejected with 400, recorded with
 *    signatureValid=false, and no signatureValid=true row is created.
 */

