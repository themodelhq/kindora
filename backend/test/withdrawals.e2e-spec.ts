  /**
   * REAL fresh-MFA flow against real Redis (fail-closed): enroll (idempotent),
   * confirm with a current TOTP code, exchange the next step's code for a
   * single-use challenge token. Returns the x-mfa-challenge header value.
   */
  function totpCode(secretBase32: string, stepOffset = 0): string {
    const buf = base32Decode(secretBase32.replace(/=+$/, ''));
    const counter = BigInt(Math.floor(Date.now() / 1000 / TOTP_STEP_SECONDS)) + BigInt(stepOffset);
    return hotp(buf, counter);
  }

  // Enrollment secret per bearer token — the API returns it exactly once by
  // design, so the helper caches it to exchange later challenge codes for the
  // SAME account (freshMfa is called multiple times per admin in this suite).
  const enrolledSecrets = new Map<string, string>();

  // Exchange the CURRENT counter's code (or the next counter's) for a single-use
  // challenge token. The server accepts only counters within ±1 of now and a
  // verified counter is replay-locked — so when enroll+earlier challenges already
  // consumed both verifiable counters of this 30s window, the helper waits for
  // the next window instead of hammering (bounded to 3 windows).
  async function exchangeChallenge(bearer: string, purpose: string, scope: string, secretBase32: string): Promise<string> {
    for (let win = 0; win < 3; win++) {
      for (const off of [0, 1]) {
        const attempt = await request(app.getHttpServer())
          .post('/api/v1/mfa/challenge')
          .set('Authorization', `Bearer ${bearer}`)
          .send({ purpose, scope, code: totpCode(secretBase32, off) });
        if (attempt.status === 200 || attempt.status === 201) {
          return attempt.body.challengeToken as string;
        }
        // 403 replay/window rejections and rare 400 boundary races are both
        // TRANSIENT for the helper: wait out the TOTP window and retry with
        // the next window's counter (bounded — never loops forever).
      }
      // Wait out the current TOTP window; the next window offers a fresh counter.
      await new Promise((r) => setTimeout(r, 30000 - (Date.now() % 30000) + 250));
    }
    throw new Error('No usable TOTP counter for MFA challenge after 3 windows');
  }

  async function freshMfa(bearer: string, purpose: string, scope: string): Promise<string> {
    const status = await request(app.getHttpServer())
      .get('/api/v1/mfa/status')
      .set('Authorization', `Bearer ${bearer}`)
      .expect(200);
    let secret = enrolledSecrets.get(bearer);
    if (!status.body.active) {
      const enroll = await request(app.getHttpServer())
        .post('/api/v1/mfa/enroll')
        .set('Authorization', `Bearer ${bearer}`)
        .expect([200, 201]);
      secret = enroll.body.secret as string;
      enrolledSecrets.set(bearer, secret);
      await request(app.getHttpServer())
        .post('/api/v1/mfa/confirm')
        .set('Authorization', `Bearer ${bearer}`)
        .send({ code: totpCode(secret) })
        .expect([200, 201]);
    } else if (!secret) {
      // Active but this process never saw the secret (persistent DB from a
      // previous run). The secret is not retrievable by design — fail loudly.
      throw new Error(
        'Account already has active MFA whose enrollment secret this test run never received — use a fresh account for MFA-bound assertions',
      );
    }
    return exchangeChallenge(bearer, purpose, scope, secret!);
  }

