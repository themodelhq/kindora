    expect(res.body.dualApprovalRequired).toBe(true);

    // The first approver CANNOT also be the second approver (loophole removed).
    const sameAdminToken = await freshMfa(admin2Token, 'PAYOUT_SECOND_APPROVAL', withdrawalId);
    const selfSecond = await request(app.getHttpServer())
      .post(`/api/v1/withdrawals/${withdrawalId}/second-approval`)
